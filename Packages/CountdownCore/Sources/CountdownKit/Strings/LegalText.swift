    /// 这份清单描述的是**上线时的目标状态**，不是当前代码的状态。
    ///
    /// 微信 / QQ 的 SDK 目前一行都还没接进来（`CountdownPro/Auth` 下只有界面）。
    /// 之所以先把清单写全，是因为"接 SDK"和"更新清单"分开做时，
    /// 后者一定会被漏掉 —— 漏掉的后果是清单与实际行为不符，这在合规抽查里是硬伤。
    ///
    /// 接入时要守住的那条约束写在清单最后一段里：**延迟初始化**。
    /// 微信和 QQ 的 SDK 默认会在 App 启动时就采集设备信息，
    /// 一旦按默认方式接进去，"不注册就不收集任何信息"这句话当场就不成立了 ——
    /// 而那是这份隐私政策里最重要的一句。
