/// 用户协议、隐私政策与两份清单的**草案**。
///
/// # 这份文件的性质
/// 它是开发方按 App 的实际行为逐条写出来的一份底稿，**不是法律意见**。
/// 上线前必须交由律师或合规顾问审核、补齐主体信息，并替换掉文中所有
/// `⟪待补文案：…⟫` 占位符。
///
/// # 为什么开发方要先写一版，而不是直接等律师
/// 隐私政策里唯一不能错的是**"我们到底收了什么"**，而这件事只有代码知道。
/// 让不看代码的人从零起草，写出来的必然是一份通用模板 ——
/// 通用模板会为了安全起见把"可能收集设备信息、位置信息"全写上，
/// 而这个 App 一样都不收。写多了不是谨慎，是失真：
/// 用户按那份文本理解这个产品，会得出一个完全错误的印象，
/// 监管按那份文本核对实际行为，也一样对不上。
///
/// 所以这里的分工是：**事实由代码提供，措辞与法律责任由律师定。**
///
/// # 三条写作时守住的底线
/// 1. **只写代码里真的做了的事。** 没接的 SDK 不写，没收的字段不写，
///    "可能收集"这种给自己留余地的写法一律不用。
/// 2. **不知道的留占位符。** 运营主体、备案号、联系方式、数据存储地、
///    生效日期 —— 这些开发方无权决定，编一个上去比空着危险得多。
/// 3. **句子要能被一个高中生读懂。** 这份文本的读者是学生和家长，不是同行。
public enum LegalText {

    /// 每一份文本的开头都顶着这句。
    ///
    /// 它必须在**正文里**，不能只写在代码注释里 —— 注释拦不住任何人把文本复制去提审。
    /// 删掉这一行的动作是显眼的、需要解释的，这正是它存在的意义。
    public static let draftBanner = """
    ⟪草案｜本文本由开发方依 App 实际行为草拟，尚未经法律顾问审核，不得作为正式版本发布。⟫

    """

