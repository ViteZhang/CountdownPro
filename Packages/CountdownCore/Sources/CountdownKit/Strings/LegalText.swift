    // MARK: - 隐私政策

    public static var privacyPolicy: String {
        draftBanner + """
        生效日期：\(effectiveDate)
        运营方：\(entity)

        这份政策说明「\(Strings.productName)」会收集什么、不会收集什么，以及为什么。
        它按本应用的实际行为逐条写成：没做的事一句都不写，也不为了保险起见留模糊表述。

        一、不注册时，我们不收集你的任何个人信息

        你的考试信息、每天的记录、心里话、未来信件，全部只保存在你的手机本机
        （以及供小组件读取的应用组容器）。它们不会离开你的设备。

        这个状态下，本应用只有一个网络请求，见下一条。

        二、同考人数是匿名的

        为了显示"今天有多少人和你考同一场考试"，本应用会上报一次计数。

        这次上报**只包含一个计数事件**，不包含设备标识符、不包含你的账号、
        不包含考试之外的任何信息，因此我们无法从中识别或还原到具体的某个人，
        也无法把两次上报关联到同一台设备。

        当人数少于 1 万时，这个模块整块不显示 —— 数字太小时的估算不可靠，
        我们宁愿不说，也不放大。

        三、注册账号后，我们收集这些

        1. 手机号（用手机号注册时）：用于登录、找回账号、接收验证码。
           你的手机号在服务端加密存储，本机只保留后四位用于展示。
        2. 第三方账号标识（用微信 / QQ / Apple 注册时）：由对应平台返回的用户标识，
           用于识别你的账号。我们不会获取你在这些平台上的好友关系、聊天内容或其他信息。
        3. 是否年满 14 周岁：**只保存一个"是"或"否"，不保存你的出生日期。**
           它只用于判断是否需要取得监护人同意。
        4. 你选择同步的备考数据：考试信息、每日记录、心里话、未来信件（密文）。

        四、我们不收集这些

        位置信息、通讯录、相册内容、摄像头、麦克风、短信、通话记录、
        已安装应用列表、剪贴板内容、广告标识符（IDFA）。

        本应用不接入任何广告 SDK，也不接入任何第三方统计或用户行为分析 SDK。

        五、需要你授权的两项系统权限

        1. 通知：用于在几个关键节点提醒你（每个备考周期不超过 6 次），以及信件到期时提醒。
           不授权不影响任何功能。
        2. 相册写入：只在你点击"保存图片"时申请，且只有写入权限。
           我们无法读取你相册里的任何内容。

        六、未来信件我们读不到

        未开启的信以 AES-GCM 加密后存储，密钥保存在你手机的系统钥匙串中，
        不随备份导出、不随 iCloud 同步。

        在开启日到来之前，任何界面、任何调试路径、任何导出文件里都不存在信的明文，
        我们也不例外。

        七、数据存储在哪、存多久

        存储地区：\(storageRegion)
        我们只在为你提供服务所必需的期间内保存你的个人信息。
        你注销账号后，我们会删除服务器上属于你的数据。

        八、我们会不会把信息给别人

        不会出售、不会出租。
        本应用接入的第三方 SDK 及其涉及的信息，逐项列在《第三方信息共享清单》里。
        除法律法规明确要求外，我们不会向任何第三方提供你的个人信息。

        九、你的权利

        1. 查阅与复制：设置页的"导出我的数据"可以把全部记录导出为一个文件，
           无论你是否注册账号。导出文件里未开启的信仍是密文。
        2. 更正：考试信息可在应用内直接修改。
        3. 删除：心里话可以单条删除；考试可以连同其记录一并删除。
        4. 注销账号：注销后服务器上的数据会被删除。
        5. 撤回授权：通知和相册权限可以随时在系统设置里关闭。

        十、未成年人

        如果你不满 14 周岁，请在监护人同意后再注册账号。
        我们只收集判断年龄所必需的那一个布尔值，不收集出生日期。
        监护人可以通过下方联系方式要求查阅或删除相关信息。

        十一、这份政策的更新

        政策更新时，我们会在应用内显著位置提示。涉及收集范围变化的，会重新征得你的同意。

        十二、联系我们

        \(contact)
        """
    }

